// Reads plugins/*/plugin.toml and writes web/src/plugins.gen.ts: every plugin's manifest and its frontend export.
// Run: bun scripts/gen-plugins.ts  (`bun run build` in web/ runs it first; a test fails when the file is stale.)
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
export const outPath = resolve(root, "web/src/plugins.gen.ts");

const TAGS = ["public", "staff", "admin"];

interface Manifest {
  name: string;
  layer: number;
  version: string;
  tags: string[];
  uses: string[];
  emits: string[];
  listens: string[];
  slots: string[];
  fills: string[];
  widgets: string[];
  screens: Array<{ name: string; path: string; tag: string }>;
}

function strings(v: unknown, field: string, who: string): string[] {
  if (!Array.isArray(v) || v.some((x) => typeof x !== "string")) throw new Error(`${who}: "${field}" must be a list of strings`);
  return v as string[];
}

export function readManifests(rootDir: string = root): Manifest[] {
  const dir = resolve(rootDir, "plugins");
  const out: Manifest[] = [];
  for (const folder of readdirSync(dir).sort()) {
    const file = resolve(dir, folder, "plugin.toml");
    if (!existsSync(file)) continue;
    const who = `plugins/${folder}/plugin.toml`;
    const raw = Bun.TOML.parse(readFileSync(file, "utf8")) as Record<string, unknown>;
    if (raw.name !== folder) throw new Error(`${who}: name "${String(raw.name)}" must equal the folder name "${folder}"`);
    if (typeof raw.layer !== "number") throw new Error(`${who}: "layer" must be a number`);
    if (typeof raw.version !== "string") throw new Error(`${who}: "version" must be a string`);
    const tags = strings(raw.tags, "tags", who);
    for (const tag of tags) if (!TAGS.includes(tag)) throw new Error(`${who}: unknown tag "${tag}"`);
    const screensRaw = raw.screens;
    if (!Array.isArray(screensRaw)) throw new Error(`${who}: "screens" must be a list`);
    const screens = screensRaw.map((s) => {
      const o = s as Record<string, unknown>;
      if (typeof o.name !== "string" || typeof o.path !== "string" || typeof o.tag !== "string" || !TAGS.includes(o.tag)) {
        throw new Error(`${who}: every screen needs name, path and a tag of ${TAGS.join(", ")}`);
      }
      return { name: o.name, path: o.path, tag: o.tag };
    });
    out.push({
      name: folder,
      layer: raw.layer,
      version: raw.version,
      tags,
      uses: strings(raw.uses, "uses", who),
      emits: strings(raw.emits, "emits", who),
      listens: strings(raw.listens, "listens", who),
      slots: strings(raw.slots, "slots", who),
      fills: strings(raw.fills, "fills", who),
      widgets: strings(raw.widgets, "widgets", who),
      screens,
    });
  }
  // Lower layers first: slot fillers then render in layer order.
  out.sort((a, b) => a.layer - b.layer || a.name.localeCompare(b.name));

  // A fill "<plugin>/<slot>" must name a slot that plugin declares; "platform/*" is a backend-only slot.
  const declared = new Set(out.flatMap((m) => m.slots.map((s) => `${m.name}/${s.replace(/^(screen|api):/, "")}`)));
  for (const m of out) {
    for (const s of m.slots) if (!/^(screen|api):[a-z_]+$/.test(s)) throw new Error(`plugins/${m.name}/plugin.toml: bad slot "${s}"`);
    for (const f of m.fills) {
      if (!f.startsWith("platform/") && !declared.has(f)) throw new Error(`plugins/${m.name}/plugin.toml: fill "${f}" names no declared slot`);
    }
  }
  return out;
}

export function renderPlugins(rootDir: string = root): string {
  const manifests = readManifests(rootDir);
  const lines: string[] = [
    "// Generated by scripts/gen-plugins.ts from plugins/*/plugin.toml. Do not edit.",
    "// Lower layers first. Each entry joins a plugin's manifest with the `plugin` its frontend exports.",
    'import type { PluginManifest } from "./shell/contract";',
    'import type { RegisteredPlugin } from "./shell/plugin";',
  ];
  for (const m of manifests) lines.push(`import { plugin as p_${m.name} } from "@arena/${m.name}";`);
  const list = (xs: string[]) => `[${xs.map((x) => JSON.stringify(x)).join(", ")}]`;
  lines.push("", "export const plugins: RegisteredPlugin[] = [");
  for (const m of manifests) {
    lines.push(
      "  {",
      "    manifest: {",
      `      name: ${JSON.stringify(m.name)},`,
      `      layer: ${m.layer},`,
      `      version: ${JSON.stringify(m.version)},`,
      `      tags: ${list(m.tags)},`,
      `      uses: ${list(m.uses)},`,
      `      emits: ${list(m.emits)},`,
      `      listens: ${list(m.listens)},`,
      `      slots: ${list(m.slots)},`,
      `      fills: ${list(m.fills)},`,
      `      widgets: ${list(m.widgets)},`,
      m.screens.length === 0 ? "      screens: []," : "      screens: [",
      ...(m.screens.length === 0
        ? []
        : [...m.screens.map((s) => `        { name: ${JSON.stringify(s.name)}, path: ${JSON.stringify(s.path)}, tag: ${JSON.stringify(s.tag)} },`), "      ],"]),
      "    } satisfies PluginManifest,",
      `    plugin: p_${m.name},`,
      "  },",
    );
  }
  lines.push("];", "");
  return lines.join("\n");
}

if (import.meta.main) {
  writeFileSync(outPath, renderPlugins());
  console.log(`wrote ${outPath}`);
}

// Turns the front matter of DESIGN.md into CSS custom properties.
// Writes platform/design/src/tokens.css. Run: bun scripts/gen-tokens.ts
// Names: colors -> --color-<k>, typography -> --type-<k>-<prop>, rounded -> --radius-<k>,
// spacing -> --space-<k>, components -> --component-<k>-<prop>. A "{section.key}" value becomes var(...).
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dir, "..");

type Tokens = Record<string, unknown>;

export function parseFrontMatter(md: string): Tokens {
  const m = md.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
  if (!m) throw new Error("DESIGN.md has no front matter");
  return Bun.YAML.parse(m[1]!) as Tokens;
}

export function kebab(s: string): string {
  return s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
}

// DESIGN.md says fontFeature; CSS says font-feature-settings.
function cssProp(camel: string): string {
  const k = kebab(camel);
  return k === "font-feature" ? "font-feature-settings" : k;
}

/** CSS custom property name for a front matter path like ["colors", "coin"]. */
export function varName(path: string[]): string {
  const [section, ...rest] = path;
  const names = rest.map(kebab);
  switch (section) {
    case "colors":
      return `--color-${names.join("-")}`;
    case "rounded":
      return `--radius-${names.join("-")}`;
    case "spacing":
      return `--space-${names.join("-")}`;
    case "typography":
    case "components": {
      const prefix = section === "typography" ? "type" : "component";
      return `--${prefix}-${names.slice(0, -1).join("-")}-${cssProp(rest[rest.length - 1]!)}`;
    }
    default:
      throw new Error(`unknown token section "${section}"`);
  }
}

/** Turns a raw token value into CSS. References {a.b.c} become var(--...). */
export function cssValue(prop: string, raw: unknown): string {
  const s = String(raw);
  const ref = s.match(/^\{([^}]+)\}$/);
  if (ref) return `var(${varName(ref[1]!.split("."))})`;
  if (prop === "font-family" || prop === "font-feature-settings") return `"${s}"`;
  return s;
}

const FALLBACK_STACK: Record<string, string> = {
  "Press Start 2P": "ui-monospace, monospace",
  "Golos Text": "system-ui, sans-serif",
  "JetBrains Mono": "ui-monospace, monospace",
};

export function renderTokens(md: string): string {
  const t = parseFrontMatter(md);
  const lines: string[] = [];

  for (const section of ["colors", "rounded", "spacing"] as const) {
    lines.push(`  /* ${section} */`);
    for (const [k, v] of Object.entries(t[section] as Tokens)) {
      lines.push(`  ${varName([section, k])}: ${cssValue("", v)};`);
    }
  }
  for (const section of ["typography", "components"] as const) {
    lines.push(`  /* ${section} */`);
    for (const [k, props] of Object.entries(t[section] as Record<string, Tokens>)) {
      for (const [p, v] of Object.entries(props)) {
        lines.push(`  ${varName([section, k, p])}: ${cssValue(cssProp(p), v)};`);
      }
    }
  }

  const classes: string[] = [];
  for (const [k, props] of Object.entries(t.typography as Record<string, Tokens>)) {
    const family = String(props.fontFamily);
    const decl = Object.keys(props).map((p) => {
      const prop = cssProp(p);
      const v = `var(${varName(["typography", k, p])})`;
      return prop === "font-family" ? `font-family: ${v}, ${FALLBACK_STACK[family] ?? "sans-serif"};` : `${prop}: ${v};`;
    });
    classes.push(`.t-${kebab(k)} {\n  ${decl.join("\n  ")}\n}`);
  }

  return [
    "/* Generated by scripts/gen-tokens.ts from the front matter of DESIGN.md. Do not edit. */",
    ":root {",
    ...lines,
    "}",
    "",
    "/* Type styles: one class per typography token. */",
    ...classes,
    "",
  ].join("\n");
}

export const tokensPath = resolve(root, "platform/design/src/tokens.css");
export const designPath = resolve(root, "DESIGN.md");

if (import.meta.main) {
  writeFileSync(tokensPath, renderTokens(readFileSync(designPath, "utf8")));
  console.log(`wrote ${tokensPath}`);
}
